// Builds dist/: custom-css.css (theme + Lucide icon overrides) and the font files it references.
import { readFileSync, writeFileSync, mkdirSync, cpSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lucide = join(root, "node_modules/lucide-static/font");
const codepoints = JSON.parse(readFileSync(join(lucide, "codepoints.json"), "utf8"));
const map = JSON.parse(readFileSync(join(root, "src/icons-map.json"), "utf8"));

const missing = Object.entries(map).filter(([, l]) => !(l in codepoints));
if (missing.length) {
  console.error("Unknown Lucide icons:", missing.map(([fa, l]) => `${fa} -> ${l}`).join(", "));
  process.exit(1);
}

// Group Font Awesome classes by Lucide icon so each glyph's content is written once.
const byIcon = new Map();
for (const [fa, l] of Object.entries(map)) byIcon.set(l, [...(byIcon.get(l) ?? []), fa]);

const rules = [...byIcon].map(([l, fas]) => {
  const sel = fas.map((fa) => `.fa-${fa}::before`).join(",\n");
  return `${sel} { content: "\\${codepoints[l].toString(16)}"; }`;
});

const icons = `
/* ---------- Lucide icons in place of Font Awesome (generated by scripts/build.mjs) ---------- */

@font-face {
    font-family: "lucide";
    font-style: normal;
    font-weight: 400;
    font-display: swap;
    src: url("/fonts/lucide/lucide.woff2") format("woff2");
}

/* Every mapped class switches font; icons without a mapping keep their Font Awesome glyph. */
${[...Object.keys(map)].map((fa) => `.fa-${fa}::before`).join(",\n")} {
    font-family: "lucide" !important;
    font-weight: 400 !important;
    font-style: normal;
    line-height: 1;
    /* Lucide's glyphs sit high in the em box next to Font Awesome's (and next to text); nudge them down. */
    position: relative;
    top: 0.16em;
}

${rules.join("\n")}
`;

rmSync(join(root, "dist"), { recursive: true, force: true });
mkdirSync(join(root, "dist/fonts/lucide"), { recursive: true });
writeFileSync(join(root, "dist/custom-css.css"), readFileSync(join(root, "src/theme.css"), "utf8") + icons);
cpSync(join(root, "src/fonts/inter"), join(root, "dist/fonts/inter"), { recursive: true });
cpSync(join(lucide, "lucide.woff2"), join(root, "dist/fonts/lucide/lucide.woff2"));
cpSync(join(root, "node_modules/lucide-static/LICENSE"), join(root, "dist/fonts/lucide/LICENSE"));
console.log(`dist/ built: ${Object.keys(map).length} mapped Font Awesome classes -> ${byIcon.size} Lucide icons`);
